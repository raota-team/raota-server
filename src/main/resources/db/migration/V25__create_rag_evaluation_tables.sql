CREATE TABLE tb_rag_evaluation_run (
    run_id VARCHAR(36) NOT NULL,
    dataset_version VARCHAR(64) NOT NULL,
    split_name VARCHAR(20) NOT NULL,
    status VARCHAR(30) NOT NULL,
    idempotency_key VARCHAR(128) NULL,
    idempotency_expires_at DATETIME(6) NULL,
    server_commit VARCHAR(64) NULL,
    app_contract_version VARCHAR(64) NULL,
    vector_index_version VARCHAR(128) NULL,
    model_metadata JSON NULL,
    aggregate_metrics JSON NULL,
    fatal_error TEXT NULL,
    started_at DATETIME(6) NULL,
    completed_at DATETIME(6) NULL,
    created_at DATETIME(6) NOT NULL,
    PRIMARY KEY (run_id),
    UNIQUE KEY uk_rag_evaluation_run_idempotency_key (idempotency_key),
    KEY idx_rag_evaluation_run_status_created (status, created_at)
);

CREATE TABLE tb_rag_evaluation_case_result (
    id BIGINT NOT NULL AUTO_INCREMENT,
    run_id VARCHAR(36) NOT NULL,
    case_id VARCHAR(100) NOT NULL,
    case_type VARCHAR(20) NOT NULL,
    status VARCHAR(20) NOT NULL,
    request_json JSON NOT NULL,
    expected_json JSON NOT NULL,
    response_json JSON NULL,
    evidence_json JSON NULL,
    metrics_json JSON NULL,
    auto_judgement_json JSON NULL,
    final_review_json JSON NULL,
    latency_ms BIGINT NULL,
    error_type VARCHAR(120) NULL,
    error_message TEXT NULL,
    reviewer_member_id BIGINT NULL,
    reviewed_at DATETIME(6) NULL,
    created_at DATETIME(6) NOT NULL,
    PRIMARY KEY (id),
    UNIQUE KEY uk_rag_eval_case_run_case (run_id, case_id),
    KEY idx_rag_eval_case_run (run_id, id),
    KEY idx_rag_eval_case_status (status)
);
